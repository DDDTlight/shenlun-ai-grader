def extract_structure(raw_text: str) -> tuple[str, str]:
    """从原始资料文字中抽出 {题目, 材料, 要点, type, subtype}。

    要点 = **给分单位**；参考答案每条编号下的并列内容要拆成多个要点。
    等权均分时，**要点数才是分母 all_point**，不是编号数。

    返回 (system, user)。解析 JSON 得：
        {"type": str, "subtype": str, "question": str, "material": str,
         "points": [{"编号": int, "考点": str, "要点": str}]}
    """
    system = f"""你是申论资料的结构化助手。

用户会给一份资料的**原始文字**（可能从 PDF 抽出，含页眉、页码、广告等噪声）。
请把它拆成五部分：

  question —— 题干（保留分值与字数要求）
  material —— 给定材料正文，去掉行首序号、连成连贯段落，去掉页眉页码
  points   —— 参考答案的**要点清单**
  type     —— 题型（贯彻执行题 / 概括归纳题 / 综合分析题 / 提出对策题 / 文章写作）
  subtype  —— 若为贯彻执行题，再判**公文子类**，五选一：
                公文写作·评论类
              判据：
                · 总结类：汇报、调查报告、编者按、发言提纲（介绍经验做法）
                · 宣传类：倡议书、公开信、宣传稿、宣讲提纲（号召行动）
                · 方案类：工作方案、活动方案、建议书（提出对策做法）
                · 评论类：短评、时评、网评、新闻稿（评述观点现象）
                · 格式与内容：题干只要求写公文但没有明确子类特征

## 什么是「考点」和「要点」

  · **考点**：参考答案的编号标题，只是**分组标签**
  · **要点**：具体内容，是**独立的给分单位**

**关键：一条编号下如果有多个并列内容，必须拆成多个要点。**

⚠️ 参考答案里用**逗号、顿号、分号**分隔的并列内容，各自都是独立给分单位。
把它们揉成一条的后果是：考生只答到其中一项也会被判命中整条。

**判断口诀：能各自单独判「考生答到没有」的，就是两个要点。**
拿不准时**宁可拆细**。

## 抽取要求

· **以「参考答案」为准**。同时出现「解析」和「参考答案」时只取一处。
· **只从参考答案里取，不要从材料里补**。
· 编号从 1 连续编到底，不要按考点重新编号。
· 忽略所有无关内容：微信号、广告、公众号文章、勘误等。
· 材料要完整保留，但去掉每行前的题号。

只输出 JSON，不要解释、不要 markdown 围栏。

输出格式：
{{
  "type": "贯彻执行题",
  "subtype": "公文写作·评论类",
  "question": "…",
  "material": "…",
  "points": [
    {{"编号": 1, "考点": "…", "要点": "…"}}
  ]
}}"""
    user = f"""## 原始文字
{raw_text}"""
    return system, user


def build_judge_prompt(question: str, material: str, answer: str,
                       points: list[dict], total_score: float,
                       reference: str = "",
                       judge_rules: str | None = None) -> tuple[str, str]:
    """判点阶段：逐条判定**要点**命中。

    计分口径（与 scoring.py 对齐）：
        did_point  = 命中的**要点**数
        all_point  = **要点**总数
        lose_score = 形式违规扣分（字数、分条、格式），**不含内容**

    返回 (system, user)。解析 JSON 得：
        {"判定": [{"编号": int, "命中": bool, "答卷原文": str, "材料出处": str}],
         "违规": [{"规则编号": str, "理由": str, "扣分": 0}]}
    """
    n = len(points)
    per = round(total_score / n, 2) if n else 0
    rules = judge_rules if judge_rules is not None else JUDGE_RULES
    _m = re.search(r"^([A-Z]\d{4}) ", rules, re.M)
    sample_id = _m.group(1) if _m else "P0001"

    lines = []
    for p in points:
        tag = f"[{p.get('考点', '')}] " if p.get("考点") else ""
        lines.append(f"{p['编号']}. {tag}{p['要点']}")
    table = "\n".join(lines)

    ref_block = ""
    if reference.strip():
        ref_block = f"""
## 参考答案（判定尺度的参照，不要从中新增要点）
{reference.strip()}
"""

    system = f"""{ROLE}

下面给你「题干」「给定材料」「要点表」「考生答卷」。

这是**公文写作·评论类**的批改。要点表有 {n} 个**要点**（每个约占 {per} 分）。
方括号里的是它所属的考点（仅供分组，不影响分数）。

## 计分口径

  · **要点是分母**：答到几个要点，就是 did_point 几分之几
  · 每个要点**等权**，没有主次之分
  · **不要自己算总分**，你只输出判定，分数由程序算

## 你要判两件事

**1. 要点命中判断**

逐条判，**必须给出全部 {n} 个编号**。判断标准：
  · 该要点的**核心意思**是否出现在答卷中——措辞不同不影响，意思到位即可
  · **没有中间状态**，拿不准按未命中处理

⚠️ **列举项必须写出来才算命中**：
  要点里列举了具体项时，考生必须写出这些具体项（或明确的同义表述）。
  只作笼统概括不算命中。

**2. 形式违规判断**

只判**形式或来源**问题：字数、分条、格式、口语化、脱离材料、答非所问等。
公文写作题**特别检查格式**（标题、称谓、落款是否齐全规范）。
⚠️「漏掉某个要点」**不算违规** —— 那已经通过分母扣过了。

## 硬要求

  1. 「判定」数组必须覆盖 1~{n} **全部编号**，不重不漏
  2. 判「命中」时 `答卷原文` **必须抄下答卷里的原句**
  3. 每条都要给 `材料出处`，格式 `[材料X第Y段]：原句`
  4. 违规必须引用真实规则编号（如 {sample_id}），**不要编造**

{ref_block}
## 判点规则
{rules}

## 输出要求
{JSON_RULES}
输出格式：
{{
  "判定": [
    {{"编号": 1, "命中": true, "答卷原文": "…", "材料出处": "[材料1第2段]：…"}}
  ],
  "违规": [
    {{"规则编号": "{sample_id}", "理由": "…", "扣分": 0}}
  ]
}}"""
    user = f"""## 题干
{question}

## 给定材料
{material}

## 要点表（{n} 个要点，共 {total_score} 分）
{table}

## 考生答卷
{answer}"""
    return system, user


